//! A small stroke font: text as 3D line segments, so labels, section names and values are scene
//! geometry with the model's depth – like the local axes – instead of 2D text over the view
//! (docs/12 §2.1). Glyphs live on a 4 × 6 grid; the advance is 6.

/// Polylines of a glyph on the 4 × 6 grid (x right, y up). Letters are drawn upper case.
fn glyph(c: char) -> &'static [&'static [(f32, f32)]] {
    match c.to_ascii_uppercase() {
        '0' | 'O' => &[&[(0., 0.), (4., 0.), (4., 6.), (0., 6.), (0., 0.)]],
        '1' => &[&[(1., 5.), (2., 6.), (2., 0.)]],
        '2' => &[&[(0., 6.), (4., 6.), (4., 3.), (0., 3.), (0., 0.), (4., 0.)]],
        '3' => &[&[(0., 6.), (4., 6.), (4., 0.), (0., 0.)], &[(0., 3.), (4., 3.)]],
        '4' => &[&[(0., 6.), (0., 3.), (4., 3.)], &[(4., 6.), (4., 0.)]],
        '5' | 'S' => &[&[(4., 6.), (0., 6.), (0., 3.), (4., 3.), (4., 0.), (0., 0.)]],
        '6' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.), (4., 3.), (0., 3.)]],
        '7' => &[&[(0., 6.), (4., 6.), (4., 0.)]],
        '8' => &[&[(0., 0.), (4., 0.), (4., 6.), (0., 6.), (0., 0.)], &[(0., 3.), (4., 3.)]],
        '9' => &[&[(4., 3.), (0., 3.), (0., 6.), (4., 6.), (4., 0.), (0., 0.)]],
        'A' => &[&[(0., 0.), (0., 6.), (4., 6.), (4., 0.)], &[(0., 3.), (4., 3.)]],
        'B' => &[&[(0., 0.), (0., 6.), (3., 6.), (4., 5.), (4., 4.), (3., 3.), (0., 3.)], &[(3., 3.), (4., 2.), (4., 1.), (3., 0.), (0., 0.)]],
        'C' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.)]],
        'D' => &[&[(0., 0.), (0., 6.), (3., 6.), (4., 5.), (4., 1.), (3., 0.), (0., 0.)]],
        'E' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.)], &[(0., 3.), (3., 3.)]],
        'F' => &[&[(4., 6.), (0., 6.), (0., 0.)], &[(0., 3.), (3., 3.)]],
        'G' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.), (4., 3.), (2., 3.)]],
        'H' => &[&[(0., 0.), (0., 6.)], &[(4., 0.), (4., 6.)], &[(0., 3.), (4., 3.)]],
        'I' => &[&[(2., 0.), (2., 6.)], &[(1., 0.), (3., 0.)], &[(1., 6.), (3., 6.)]],
        'J' => &[&[(4., 6.), (4., 0.), (0., 0.), (0., 2.)]],
        'K' => &[&[(0., 0.), (0., 6.)], &[(4., 6.), (0., 3.), (4., 0.)]],
        'L' => &[&[(0., 6.), (0., 0.), (4., 0.)]],
        'M' => &[&[(0., 0.), (0., 6.), (2., 3.), (4., 6.), (4., 0.)]],
        'N' => &[&[(0., 0.), (0., 6.), (4., 0.), (4., 6.)]],
        'P' => &[&[(0., 0.), (0., 6.), (4., 6.), (4., 3.), (0., 3.)]],
        'Q' => &[&[(0., 0.), (0., 6.), (4., 6.), (4., 0.), (0., 0.)], &[(2., 2.), (4., 0.)]],
        'R' => &[&[(0., 0.), (0., 6.), (4., 6.), (4., 3.), (0., 3.), (4., 0.)]],
        'T' => &[&[(0., 6.), (4., 6.)], &[(2., 6.), (2., 0.)]],
        'U' => &[&[(0., 6.), (0., 0.), (4., 0.), (4., 6.)]],
        'V' => &[&[(0., 6.), (2., 0.), (4., 6.)]],
        'W' => &[&[(0., 6.), (1., 0.), (2., 3.), (3., 0.), (4., 6.)]],
        'X' => &[&[(0., 0.), (4., 6.)], &[(0., 6.), (4., 0.)]],
        'Y' => &[&[(0., 6.), (2., 3.), (4., 6.)], &[(2., 3.), (2., 0.)]],
        'Z' => &[&[(0., 6.), (4., 6.), (0., 0.), (4., 0.)]],
        '.' => &[&[(1.6, 0.), (2.4, 0.), (2.4, 0.8), (1.6, 0.8), (1.6, 0.)]],
        ',' => &[&[(2., 0.8), (2., 0.), (1., -1.)]],
        '-' => &[&[(1., 3.), (3., 3.)]],
        '+' => &[&[(1., 3.), (3., 3.)], &[(2., 2.), (2., 4.)]],
        '/' => &[&[(0., 0.), (4., 6.)]],
        '(' => &[&[(3., 6.), (2., 5.), (2., 1.), (3., 0.)]],
        ')' => &[&[(1., 6.), (2., 5.), (2., 1.), (1., 0.)]],
        '_' => &[&[(0., 0.), (4., 0.)]],
        ':' => &[&[(2., 1.), (2., 1.6)], &[(2., 4.), (2., 4.6)]],
        '·' => &[&[(1.7, 2.7), (2.3, 2.7), (2.3, 3.3), (1.7, 3.3), (1.7, 2.7)]],
        '=' => &[&[(1., 2.), (3., 2.)], &[(1., 4.), (3., 4.)]],
        '%' => &[&[(0., 0.), (4., 6.)], &[(0., 6.), (0., 5.)], &[(4., 0.), (4., 1.)]],
        '|' => &[&[(2., -1.), (2., 7.)]],
        '#' => &[&[(1., 0.), (1., 6.)], &[(3., 0.), (3., 6.)], &[(0., 2.), (4., 2.)], &[(0., 4.), (4., 4.)]],
        // Anything else (and space): an empty cell.
        _ => &[],
    }
}

/// Grid units per character (glyph 4 + gap 2) and the glyph height.
pub const ADVANCE: f64 = 6.0;
pub const HEIGHT: f64 = 6.0;

/// `text` as 3D segments, centred on `centre`, written along `right` with `up` as the glyph's up
/// direction (both unit vectors); `height` is the glyph height in world units.
pub fn text_segments(text: &str, centre: [f64; 3], right: [f64; 3], up: [f64; 3], height: f64) -> Vec<[[f64; 3]; 2]> {
    let unit = height / HEIGHT;
    let n = text.chars().count() as f64;
    let width = (n * ADVANCE - (ADVANCE - 4.0)).max(0.0);
    let at = |x: f64, y: f64| {
        let (dx, dy) = ((x - width / 2.0) * unit, (y - HEIGHT / 2.0) * unit);
        [0, 1, 2].map(|i| centre[i] + right[i] * dx + up[i] * dy)
    };
    let mut out = Vec::new();
    for (k, c) in text.chars().enumerate() {
        let x0 = k as f64 * ADVANCE;
        for stroke in glyph(c) {
            for w in stroke.windows(2) {
                out.push([at(x0 + f64::from(w[0].0), f64::from(w[0].1)), at(x0 + f64::from(w[1].0), f64::from(w[1].1))]);
            }
        }
    }
    out
}

/// Whether `c` has a glyph (anything else is drawn as a gap).
pub fn has_glyph(c: char) -> bool {
    c == ' ' || !glyph(c).is_empty()
}
